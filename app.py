import streamlit as st
import pickle

st.set_page_config(page_title="Movie MatchMaker", page_icon="🎬", layout="centered")

# Load the saved model and dataframe from your notebook
@st.cache_resource
def load_data():
    movies = pickle.load(open('movies.pkl', 'rb'))
    similarity = pickle.load(open('similarity.pkl', 'rb'))
    return movies, similarity

movies, similarity = load_data()

# Recommendation logic matching matchmaker.ipynb
def recommend(movie):
    index = movies[movies['title'] == movie].index[0]
    distances = list(enumerate(similarity[index]))
    movies_list = sorted(distances, reverse=True, key=lambda x: x[1])[1:6]

    recommended_movies = []
    for i in movies_list:
        recommended_movies.append(movies.iloc[i[0]].title)
    return recommended_movies

# Streamlit User Interface
st.title("🎬 Movie MatchMaker")
st.write("Select a movie from the dropdown to get the top 5 recommendations:")

movie_list = movies['title'].values
selected_movie = st.selectbox(
    "Type or select a movie:",
    movie_list
)

if st.button("Recommend", type="primary"):
    recommendations = recommend(selected_movie)
    st.subheader(f"Movies similar to '{selected_movie}':")
    for idx, item in enumerate(recommendations, 1):
        st.write(f"**{idx}.** {item}")

